/** Контракт протокола — пишется в .pi/pipeline/PROTOCOL.md и bootstrap'ится в агентов. */
export const PROTOCOL = `# PROTOCOL — pipeline worker → planner → judge

Conductor (pi-расширение commander) шлёт в tmux-пани сообщения вида
\`[pipeline T-id R-n → роль] Прочитай <brief-файл> и выполни...\`.
Задачи из цепочки узнавай по префиксу \`[pipeline\` — остальное может быть
личным разговором пользователя.

Общие правила:
- Получил \`[pipeline ...]\` → читай brief-файл, выполняй, делай ФИНАЛЬНЫЙ ШАГ.
- ФИНАЛЬНЫЙ ШАГ — создать свой done-файл — ОБЯЗАТЕЛЕН, иначе conductor
  упрётся в таймаут и эскалирует задачу человеку. Делай его только после
  валидного артефакта.
- Внутри pipeline не задавай вопросов пользователю — вопросы пиши в свой
  артефакт, их получит следующая роль.
- Артефакты — строго по шаблонам ниже, в указанный в brief файле.

## Q&A (mid-round, worker ↔ planner)
Только worker имеет право спросить архитектора в середине этапа (planner и
judge вопросов не задают). Если решение влияет на архитектуру и spec его не
покрывает — НЕ гадь и НЕ принимай решение сам:
1) Напиши вопросы в \`round-N/ask-worker.md\`: нумерованные \`[Q1]..\`, каждый
   самодостаточный (контекст + какое решение нужно + что сделаешь при ответе X).
2) Продолжай всё, что не зависит от ответа. Конечный артефакт и финальный шаг
   делай только после ответа.
3) Ответ придёт сообщением \`[pipeline T-id R-n → worker] Ответы архитектора: <файл>...\`.
Максимум 3 Q&A за этап — если решений надо больше, вероятно, spec неполный:
зафикси то, что можешь, и в отчёте статус \`done-with-questions\`.

Planner: по сообщению \`[pipeline T-id R-n → planner Q&A]\` — read-only, код не
править. Ответ: в файл, указанный в сообщении, по одному блоку на вопрос:
\`[Qx] → решение + обоснование (ссылка на код/spec)\`. Финальный шаг — из того
же сообщения (done-файл Q&A).

## spec (пишет пользователь перед запуском)
\`\`\`
## Цель — 1–3 предложения: что считается «сделано»
## Критерии приёмки — observable-чеклист: файл/тест/поведение; каждый пункт проверяем
## Референсы — файлы/паттерны, на которые опираться
## Правила — запреты: не трогать X, не добавлять зависимость Y
## Границы — что явно НЕ входит в задачу
\`\`\`

## worker
Правит код. Выход — worker-report.md:
\`\`\`
# Round N — Worker
## Статус: done | done-with-questions | blocked
## Изменения — каждый тронутый файл: что и почему
## Ключевые решения — решение → обоснование
## Ответы на требования — на каждый R-пункт: сделано / не сделано + причина
## Открытые вопросы — (опционально; если есть — статус done-with-questions)
\`\`\`
Правила: список «Изменения» должен совпадать с git diff; невыполненное
R-требование — НИКОГДА не молчать, записать «не сделано, причина».

## planner
Read-only: код НЕ правит. Выход — planner-decision.md:
\`\`\`
# Round N — Planner
## Вердикт по архитектуре: approve | changes-needed
## Ответы на вопросы — на каждый открытый вопрос worker: обязательно ответ
## Требования к раунду N+1 — [R1]..[Rn]; каждое однозначное и проверяемое судьёй
\`\`\`
«Добавь валидацию» — не требование. «Проверь поле X, при ошибке брось Y с
сообщением Z» — требование.

## judge
Read-only. НЕ читает и не учитывает отчёты, обоснования и переписку агентов —
только spec (критерии приёмки, референсы, правила, границы) и код (git diff).
Выход — judge-verdict.json, валидный JSON:
\`\`\`
{
  "verdict": "pass | revise | blocked",
  "issues": [
    { "id": "I1", "sev": "blocker | major | minor",
      "spec": "ссылка на пункт spec",
      "what": "что не так",
      "file": "путь",
      "how": "как исправить" }
  ],
  "notes": "неблокирующие замечания для пользователя"
}
\`\`\`
Семантика: \`revise\` ⇔ есть ≥1 blocker/major; minor — в notes.
\`blocked\` = «не могу оценить» (spec противоречив, референс недоступен),
а не «не нравится».
`;
